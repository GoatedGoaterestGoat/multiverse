#!/usr/bin/env python3
"""Generate docs/cli/reference.md from mv2's argparse parser.

    python scripts/gen_cli_docs.py           # rewrite docs/cli/reference.md
    python scripts/gen_cli_docs.py --check   # exit 1 when it is stale

Usage lines and tables are built from the parser's actions, not from argparse's
help formatter, so the output never depends on terminal width.
"""
import argparse
import difflib
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "cli" / "reference.md"
PROG = "mv2"
HEADER = "<!-- Generated by scripts/gen_cli_docs.py; do not edit. -->"


def load_parser():
    """Build the checkout's parser with a clean, fixed environment."""
    for name in [name for name in os.environ if name.startswith("MV2_")]:
        del os.environ[name]
    # --agent defaults to this variable at parser build time; render it by name.
    os.environ["MV2_AGENT_ID"] = "$MV2_AGENT_ID"
    sys.path.insert(0, str(ROOT / "src"))
    from multiverse import cli
    return cli.parser()


def summary(text):
    """First paragraph of a help string or docstring, on one line."""
    if not text:
        return ""
    return " ".join(text.strip().split("\n\n")[0].split())


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def subcommands(parser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def options(parser):
    """Documented actions: everything except -h and subcommand dispatch."""
    return [action for action in parser._actions
            if not isinstance(action, (argparse._HelpAction, argparse._SubParsersAction))]


def takes_value(action):
    return action.nargs != 0


def metavar(action):
    if action.metavar is not None:
        return action.metavar
    if action.choices is not None:
        return "{" + ",".join(map(str, action.choices)) + "}"
    if action.option_strings:
        return action.dest.upper()
    return action.dest


def usage_part(action):
    if not action.option_strings:
        name = metavar(action)
        if action.nargs == argparse.OPTIONAL:
            return f"[{name}]"
        if action.nargs == argparse.ZERO_OR_MORE:
            return f"[{name} ...]"
        if action.nargs == argparse.ONE_OR_MORE:
            return f"{name} [{name} ...]"
        if action.nargs == argparse.REMAINDER:
            return "..."
        return name
    text = action.option_strings[0]
    if takes_value(action):
        text += f" {metavar(action)}"
    return text


def usage(parser, prefix):
    groups = {id(action): group for group in parser._mutually_exclusive_groups
              for action in group._group_actions}
    parts, done = [], set()
    actions = options(parser)
    for action in [a for a in actions if a.option_strings] + [a for a in actions if not a.option_strings]:
        group = groups.get(id(action))
        if group is not None:
            if id(group) in done:
                continue
            done.add(id(group))
            inner = " | ".join(usage_part(member) for member in group._group_actions)
            parts.append(f"({inner})" if group.required else f"[{inner}]")
        elif action.option_strings and not action.required:
            parts.append(f"[{usage_part(action)}]")
        else:
            parts.append(usage_part(action))
    return " ".join([prefix, *parts])


def default_text(action):
    value = action.default
    if value is None or value is argparse.SUPPRESS or value is False or value == []:
        return ""
    if not takes_value(action):
        return ""
    return f"`{value}`"


def help_text(action, default):
    text = summary(action.help) if action.help is not argparse.SUPPRESS else ""
    if "%(" in text:
        text = text % {"default": action.default, "prog": PROG, "dest": action.dest}
    if default:
        # The Default column carries a value the help repeats at its end.
        plain = default.strip("`")
        text = re.sub(rf"\s*\(default: {re.escape(plain)}\)$", "", text)
    if action.option_strings and action.required:
        text = f"Required. {text}".strip()
    return text


def value_text(action):
    if not action.option_strings or not takes_value(action):
        return ""
    if action.choices is not None and action.metavar is None:
        return ", ".join(f"`{choice}`" for choice in action.choices)
    text = f"`{metavar(action)}`"
    if isinstance(action, argparse._AppendAction) and "repeatable" not in (action.help or ""):
        text += " (repeatable)"
    return text


def option_text(action):
    if action.option_strings:
        return ", ".join(f"`{name}`" for name in action.option_strings)
    if action.nargs == argparse.REMAINDER:
        return f"`{action.dest} ...`"
    return f"`{metavar(action)}`"


def table(parser):
    rows = options(parser)
    if not rows:
        return ["Takes no options."]
    lines = ["| Argument | Value | Description | Default |", "| --- | --- | --- | --- |"]
    for action in rows:
        default = default_text(action)
        lines.append("| " + " | ".join(cell(part) for part in (
            option_text(action), value_text(action), help_text(action, default), default)) + " |")
    for group in parser._mutually_exclusive_groups:
        names = ", ".join(f"`{member.option_strings[0]}`" for member in group._group_actions)
        lines.append("")
        lines.append(f"Use {'exactly' if group.required else 'at most'} one of {names}.")
    return lines


def anchor(name):
    return re.sub(r"[^a-z0-9 _-]", "", name.lower()).replace(" ", "-")


def render(parser):
    commands = subcommands(parser)
    aliases = {}
    for name, sub in commands.choices.items():
        aliases.setdefault(id(sub), []).append(name)
    helps = {action.dest: summary(action.help) for action in commands._choices_actions}

    out = [HEADER, "", "# CLI reference", "",
           f"Every `{PROG}` command and option. Run `{PROG} COMMAND --help` for the same information in a terminal.", "",
           "```sh", usage(parser, PROG) + " [COMMAND] [OPTIONS]", "```", "",
           summary(parser.description), "",
           "## Global options", "",
           "Put global options before the command, as in "
           f"`{PROG} -u /path/to/project list`. Every command also takes `-h`, `--help`.", ""]
    out += table(parser)
    out += ["", "## Commands", "", "| Command | Description |", "| --- | --- |"]
    for name, sub in commands.choices.items():
        names = aliases[id(sub)]
        if name != names[0]:
            line = f"Alias for [`{names[0]}`](#{anchor(names[0])})."
        else:
            line = helps.get(name, "")
        out.append(f"| [`{name}`](#{anchor(name)}) | {cell(line)} |")

    for name, sub in commands.choices.items():
        names = aliases[id(sub)]
        out += ["", f"## {name}", ""]
        if name != names[0]:
            out.append(f"Alias for [`{names[0]}`](#{anchor(names[0])}).")
            continue
        if helps.get(name):
            out += [helps[name], ""]
        if summary(sub.description):
            out += [summary(sub.description), ""]
        out += ["```sh", usage(sub, f"{PROG} {name}"), "```", ""]
        if len(names) > 1:
            out += ["Alias: " + ", ".join(f"`{alias}`" for alias in names[1:]) + ".", ""]
        out += table(sub)
    return "\n".join(out) + "\n"


def main():
    arguments = argparse.ArgumentParser(description="Generate docs/cli/reference.md from the mv2 parser.")
    arguments.add_argument("--check", action="store_true", help="Exit 1 if the file is out of date; write nothing")
    check = arguments.parse_args().check
    text = render(load_parser())
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if check:
        if current == text:
            return 0
        relative = TARGET.relative_to(ROOT)
        diff = list(difflib.unified_diff(current.splitlines(), text.splitlines(),
                                         f"{relative} (current)", f"{relative} (generated)", lineterm=""))
        print(f"{relative} is stale; run python scripts/gen_cli_docs.py", file=sys.stderr)
        print("\n".join(diff[:40] + (["..."] if len(diff) > 40 else [])), file=sys.stderr)
        return 1
    if current != text:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
